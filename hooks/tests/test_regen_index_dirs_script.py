def test_script_case_sc_nondir_exit_one(tmp_path):
    """An argument that is not a directory is still a usage error: exit 1, message on stderr."""
    sandbox = Sandbox(tmp_path)
    plain_file = sandbox.repo / 'plain.txt'
    plain_file.write_text('x\n')

    completed = sandbox.run(plain_file)

    assert completed.returncode == 1
    assert 'not a directory' in completed.stderr
    assert completed.stdout == ''
    assert sandbox.run().returncode == 1


def test_script_case_sc_exit_zero_on_skip(tmp_path):
    """Skips never fail the run: several directories, mixed outcomes, exit 0, one line each."""
    sandbox = Sandbox(tmp_path)
    skipped = sandbox.directory('skipped')
    (skipped / 'INDEX.md').write_text('# skipped\n\nhand written\n')
    managed = sandbox.directory('managed')
    (managed / 'INDEX.md').write_text(f'# managed\n\n{IO}\nstale\n{IC}\n')

    completed = sandbox.run(skipped, managed)

    assert completed.returncode == 0, completed.stderr
    assert completed.stdout.splitlines() == [
        f'skipped (SKIPPED_NO_OPENING_MARKER): {skipped / "INDEX.md"}', f'regenerated: {managed / "INDEX.md"}']


def test_script_case_sc_prose_marker_mention_not_a_marker(tmp_path):
    """Marker text inside prose or a fenced example is not a marker: no opt-in, no takeover."""
    sandbox = Sandbox(tmp_path)
    prose = sandbox.directory('prose')
    (prose / 'INDEX.md').write_text(f'# prose\n\nUse `{IO}` and `{IC}` to opt in.\n')
    fenced = sandbox.directory('fenced')
    (fenced / 'INDEX.md').write_text(f'# fenced\n\n```\n{IO}\nexample\n{IC}\n```\n')
    generated = sandbox.directory('generated')
    (generated / 'INDEX.md').write_text(GENERATED.replace('hand annotation', f'mention of {IO} in prose'))
    untouched = {name: (directory / 'INDEX.md').read_bytes() for name, directory in
                 (('prose', prose), ('fenced', fenced))}

    completed = sandbox.run(prose, fenced, generated)

    assert completed.returncode == 0, completed.stderr
    assert completed.stdout.splitlines() == [
        f'skipped (SKIPPED_NO_OPENING_MARKER): {prose / "INDEX.md"}',
        f'skipped (SKIPPED_NO_OPENING_MARKER): {fenced / "INDEX.md"}',
        f'regenerated: {generated / "INDEX.md"}']
    assert (prose / 'INDEX.md').read_bytes() == untouched['prose']
    assert (fenced / 'INDEX.md').read_bytes() == untouched['fenced']
    text = (generated / 'INDEX.md').read_text()
    assert text.count(f'\n{IO}\n') == 1 and f'mention of {IO} in prose' in text and text.count('*Last updated:') == 1


def test_script_case_sc_bytes_unchanged_on_skip(tmp_path):
    """Every skip shape leaves the INDEX bytes and mtime alone, malformed shapes included."""
    sandbox = Sandbox(tmp_path)
    shapes = {
        'duplicate': f'{IO}\nx\n{IO}\ny\n{IC}\n',
        'reversed': f'{IC}\nmiddle\n{IO}\nstale\n',
        'near_miss': '# near\n<!--AUTO:index-stats-->\nstale\n',
        'inline_pair': f'# inline\n{IO} {IC}\n',
        'zero_bytes': '',
    }
    expected = {'duplicate': 'SKIPPED_MALFORMED_MARKERS', 'reversed': 'SKIPPED_NO_CLOSING_MARKER',
                'near_miss': 'SKIPPED_MALFORMED_MARKERS', 'inline_pair': 'SKIPPED_MALFORMED_MARKERS',
                'zero_bytes': 'SKIPPED_NO_OPENING_MARKER'}
    for name, text in shapes.items():
        directory = sandbox.directory(name)
        index = directory / 'INDEX.md'
        index.write_text(text)
        before = pinned(index)

        completed = sandbox.run(directory)

        assert completed.returncode == 0, (name, completed.stderr)
        assert completed.stdout == f'skipped ({expected[name]}): {index}\n', name
        assert (index.read_bytes(), index.stat().st_mtime_ns) == before, name
