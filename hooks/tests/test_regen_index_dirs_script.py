#!/usr/bin/env python3
"""Subprocess tests for scripts/regen-index-dirs.py.

Backlog #85: the script printed `regenerated: <INDEX>` for every directory, including the ones
regen_index() left untouched, so a run that changed nothing looked like a resync. It now
reports the status regen_index() returns: `regenerated:` only for a write, `skipped (<STATUS>):`
otherwise, and only an INDEX with no marker at all that looks generated gets markers inserted.

Isolation: the script locates its repository root from its own path, so each case runs a COPY
of the script and of the doc_sync package inside a synthetic repository root under tmp_path.
The GitHub-reserved subtree is then that root's .github, and nothing touches the real tree.
HOME and TMPDIR are redirected and the doc-sync environment variables are scrubbed.
"""

import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
SCRIPT = REPO_ROOT / 'scripts' / 'regen-index-dirs.py'
DOC_SYNC_PACKAGE = REPO_ROOT / 'hooks' / 'doc_sync'
SCRUBBED_ENV = ('CLAUDE_PROJECT_DIR', 'CLAUDE_DOC_SYNC_ROOTS', 'CLAUDE_DOC_SYNC_STATE_ROOT')
EARLIER_NS = 1_000_000_000 * 10**9

IO = '<!-- AUTO:index-stats -->'
IC = '<!-- /AUTO:index-stats -->'
GENERATED = (
    '# folder\n\n*Last updated: 2001-01-01T00:00:00Z*\n**Total entries**: 1\n**Convention**: kebab\n\n'
    '## Tree\n```\nfolder/\n└── `alpha.py` - Alpha helper.\n```\n\nhand annotation\n\n'
    '---\n*Auto-generated by doc-sync hook.*\n')


class Sandbox:
    """A synthetic repository root holding a copy of the script and of the doc_sync package."""

    def __init__(self, root):
        self.root = Path(root)
        self.home = self.root / 'home'
        self.tmp_root = self.root / 'tmp'
        self.repo = self.root / 'repo'
        for directory in (self.home, self.tmp_root, self.repo / 'scripts', self.repo / 'hooks'):
            directory.mkdir(parents=True)
        shutil.copy(SCRIPT, self.repo / 'scripts' / 'regen-index-dirs.py')
        shutil.copytree(DOC_SYNC_PACKAGE, self.repo / 'hooks' / 'doc_sync',
                        ignore=shutil.ignore_patterns('__pycache__', 'README.md', 'INDEX.md'))

    def directory(self, name='folder'):
        directory = self.repo / name
        directory.mkdir(parents=True, exist_ok=True)
        (directory / 'alpha.py').write_text('"""Alpha helper."""\n')
        return directory

    def run(self, *arguments):
        environment = {key: value for key, value in os.environ.items() if key not in SCRUBBED_ENV}
        environment.update(HOME=str(self.home), TMPDIR=str(self.tmp_root), PYTHONDONTWRITEBYTECODE='1')
        return subprocess.run(
            [sys.executable, str(self.repo / 'scripts' / 'regen-index-dirs.py'), *[str(a) for a in arguments]],
            capture_output=True, text=True, env=environment, cwd=str(self.home), timeout=120)


def pinned(path):
    os.utime(path, ns=(EARLIER_NS, EARLIER_NS))
    return path.read_bytes(), path.stat().st_mtime_ns


def test_script_case_sc_unmarkable_skipped(tmp_path):
    """An INDEX with no recognisable generated block is skipped, reported as such and left alone."""
    sandbox = Sandbox(tmp_path)
    directory = sandbox.directory()
    index = directory / 'INDEX.md'
    index.write_text('# folder\n\nhand written notes only\n')
    before = pinned(index)

    completed = sandbox.run(directory)

    assert completed.returncode == 0, completed.stderr
    assert completed.stdout == f'skipped (SKIPPED_NO_OPENING_MARKER): {index}\n'
    assert 'regenerated:' not in completed.stdout
    assert (index.read_bytes(), index.stat().st_mtime_ns) == before


def test_script_case_sc_generator_shape_marker_inserted_regenerated(tmp_path):
    """A markerless INDEX shaped like generator output gets markers around its block and is regenerated."""
    sandbox = Sandbox(tmp_path)
    directory = sandbox.directory()
    index = directory / 'INDEX.md'
    index.write_text(GENERATED)

    completed = sandbox.run(directory)

    assert completed.returncode == 0, completed.stderr
    assert completed.stdout == f'regenerated: {index}\n'
    text = index.read_text()
    assert text.count(IO) == 1 and text.count(IC) == 1
    assert text.count('*Last updated:') == 1 and 'hand annotation' in text and '2001-01-01' not in text


