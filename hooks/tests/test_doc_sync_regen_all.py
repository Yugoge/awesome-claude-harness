OPEN = '<!-- AUTO:readme-stats -->'
CLOSE = '<!-- /AUTO:readme-stats -->'
IOPEN = '<!-- AUTO:index-stats -->'
ICLOSE = '<!-- /AUTO:index-stats -->'
LEGACY_TAIL = (f'{OPEN}\n## Overview\n- **Total files**: 0\n- **Subdirectories**: 0\n'
               '- **Naming convention**: lower\n\n---\n*Auto-generated by doc-sync hook.*')


def load_command():
    spec = importlib.util.spec_from_file_location(
        'regen_folder_docs', REPO_ROOT / 'scripts' / 'regen-folder-docs.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


