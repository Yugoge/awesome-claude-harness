#!/usr/bin/env python3
"""scripts/regen-folder-docs.py and the writer behaviour it relies on.

- --check exits 1 naming a drifted file and writes nothing; a plain run regenerates it through
  the one writer, after which --check passes.
- A regeneration of an unchanged folder rewrites the same bytes (the INDEX keeps its
  Last-updated line), so --check is stable from run to run.
- The legacy doc-sync README region (opening marker, generated body, short footer, no closing
  marker) is closed and its stats recounted, whether it stands alone or follows hand text; an
  unclosed region of any other shape stays refused.

Every scenario builds its own git repository under tmp_path; HOME is redirected so nothing can
reach a real ~/.claude.
"""

