#!/usr/bin/env python3
"""Producer/consumer cross-reference test for the repair-map table
(ticket-20261001-161041-r19).

schemas/repair-map.v1.json is generated by scripts/generate-repair-map.py
(lane L8) by joining two hand-written prose docs; it only self-validates
against those two docs and never cross-references the literal finding-code
strings actually dispatched from commands/close.md / commands/commit.md
(lane L7) at *_repair_dispatch call sites. L7 introduced three new,
non-numeric finding codes that were never part of L8's source inventory,
and the repair engine's unrecognized-code path silently degrades to a
disclosure (never a hard failure), so this exact class of gap was
previously discoverable only by hitting it live.

RETIRED PRODUCER SIDE (2026-10-03, post-r19, NOT a weakening of this module):
a later /dev lane rewrote commands/close.md and commands/commit.md's finding
routing from code-keyed dispatch (`*_repair_dispatch "<code>"`,
`FINDING_CODE="<code>"`, the Verdict-branches `{code: "<code>", ...}` prose)
to path-keyed routing (`close_route_finding` / `artifact_role()` mapping a
finding's artifact `path` to a `producer_role`). Both command files now say
so explicitly: "No code, table or engine output is consulted ... Finding
codes (`commit#6`, ...) are display labels only; nothing is looked up by
code." None of the three producer shapes below exist in either file any
more -- confirmed live: zero occurrences of `_repair_dispatch`, `FINDING_CODE=`,
or `{code:` in commands/close.md or commands/commit.md. AC2/AC3/AC7's
required-code sets are therefore empty: there is nothing of that shape left
to extract, and the three extraction routines (still live, still regex-driven
against the current file content) would immediately start reporting again
the moment such a call site reappears. AC5 is consequently a vacuous pass
(the dispatched-code union is empty, so nothing can be missing from the
table) rather than the three-code KNOWN RED RESULT r19 originally documented
-- that red result named codes dispatched by a producer shape which no
longer exists to dispatch them.

NOTE on line numbers: this repo runs many concurrent /dev lanes against
commands/close.md and commands/commit.md, so their line numbers shift
between the moment a ticket is authored and the moment this test runs.
Every extraction routine below re-reads the live file content and reports
whichever line number is current at run time -- never a number frozen at
authoring time -- so AC5's failure message always cites the real, present
location of each unresolved code.
"""

from __future__ import annotations

import ast
import importlib.util
import re
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
ENGINE_SCRIPT = REPO_ROOT / "scripts" / "close-commit-repair-orchestrate.py"
CLOSE_MD = REPO_ROOT / "commands" / "close.md"
COMMIT_MD = REPO_ROOT / "commands" / "commit.md"

# Verdict-branches section (commands/close.md) -- AC7's exclusive target.
# Located by content marker, not a fixed line range: commands/close.md is a
# live, frequently-edited document (this repo runs many concurrent /dev
# lanes against it), so an absolute line range captured at ticket-authoring
# time goes stale within minutes. The section heading and the paragraph
# that follows it are the stable anchors.
VERDICT_BRANCH_SECTION_HEADING = "Verdict branches:"
VERDICT_BRANCH_SECTION_END_MARKER = "Transcript file:"

# Three distinct syntactic shapes a finding code can be dispatched in:
#   (1) a direct *_repair_dispatch "<code>" call-site literal (AC2)
#   (2) a close.md FINDING_CODE="<code>" case-statement assignment that
#       later feeds an indirected close_repair_dispatch "$FINDING_CODE" (AC3)
#   (3) a close.md Verdict-branches {code: "<code>", ...} narrative-prose
#       entry, which contains zero occurrences of "repair_dispatch" (AC7)
DIRECT_CALL_PATTERN = re.compile(r'(?:close|commit)_repair_dispatch\s+"([^"]+)"')
FINDING_CODE_ASSIGNMENT_PATTERN = re.compile(r'FINDING_CODE="([^"]+)"')
VERDICT_BRANCH_PATTERN = re.compile(r'\{code:\s*"([^"]+)"')

Location = tuple[str, int]
CodeMap = dict[str, list[Location]]


def _load_engine_module():
    spec = importlib.util.spec_from_file_location("close_commit_repair_orchestrate", ENGINE_SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


ENGINE = _load_engine_module()

# AC4: allowlisted by importing the real constant -- never re-typed here.
ALLOWLIST = {ENGINE.RESTART_LANE_SENTINEL_CODE}


def _lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8").splitlines()


def _extract_direct_literals() -> CodeMap:
    """AC2: direct *_repair_dispatch "<code>" call-site literals from both
    command files. A captured value starting with "$" is a shell-variable
    indirection, not a literal code, and is discarded here (AC3 resolves it
    separately)."""
    found: CodeMap = {}
    for rel_path, path in (("commands/close.md", CLOSE_MD), ("commands/commit.md", COMMIT_MD)):
        for lineno, line in enumerate(_lines(path), start=1):
            for match in DIRECT_CALL_PATTERN.finditer(line):
                code = match.group(1)
                if code.startswith("$"):
                    continue
                found.setdefault(code, []).append((rel_path, lineno))
    return found


def _extract_finding_code_assignments() -> CodeMap:
    """AC3: resolve close.md's $FINDING_CODE indirection (the
    `close_repair_dispatch "$FINDING_CODE"` call site) to its literal
    case-statement assignment sites, read live from the current file."""
    found: CodeMap = {}
    for lineno, line in enumerate(_lines(CLOSE_MD), start=1):
        for match in FINDING_CODE_ASSIGNMENT_PATTERN.finditer(line):
            found.setdefault(match.group(1), []).append(("commands/close.md", lineno))
    return found


def _verdict_branches_section_bounds(lines: list[str]) -> tuple[int, int]:
    """Locate the Verdict-branches section by its heading/end markers rather
    than a fixed line range (see VERDICT_BRANCH_SECTION_HEADING comment).
    Returns a 0-indexed [start, end) slice bound."""
    start_idx = None
    for i, line in enumerate(lines):
        if line.strip() == VERDICT_BRANCH_SECTION_HEADING:
            start_idx = i
            break
    assert start_idx is not None, (
        f"AC7: could not locate the {VERDICT_BRANCH_SECTION_HEADING!r} marker in commands/close.md "
        "-- the section may have been renamed; update VERDICT_BRANCH_SECTION_HEADING"
    )
    end_idx = len(lines)
    for i in range(start_idx + 1, len(lines)):
        if lines[i].startswith(VERDICT_BRANCH_SECTION_END_MARKER):
            end_idx = i
            break
    return start_idx, end_idx


def _extract_verdict_branch_codes() -> CodeMap:
    """AC7: close.md's Verdict-branches {code: "<code>", ...} narrative-prose
    idiom -- a syntactic shape distinct from AC2's call-site literals and
    never matched by DIRECT_CALL_PATTERN. The section is located dynamically
    (see _verdict_branches_section_bounds) so this survives concurrent edits
    elsewhere in commands/close.md shifting absolute line numbers."""
    found: CodeMap = {}
    lines = _lines(CLOSE_MD)
    start_idx, end_idx = _verdict_branches_section_bounds(lines)
    for offset, line in enumerate(lines[start_idx:end_idx]):
        lineno = start_idx + offset + 1
        for match in VERDICT_BRANCH_PATTERN.finditer(line):
            found.setdefault(match.group(1), []).append(("commands/close.md", lineno))
    return found


def _all_dispatched_codes() -> CodeMap:
    """Union of AC2 ∪ AC3 ∪ AC7 -- the full producer-side code inventory
    that AC5 checks against the real generated repair-map table."""
    combined: CodeMap = {}
    for extractor in (_extract_direct_literals, _extract_finding_code_assignments, _extract_verdict_branch_codes):
        for code, locations in extractor().items():
            combined.setdefault(code, []).extend(locations)
    return combined


def _format_missing_codes(missing: list[tuple[str, list[Location]]]) -> str:
    header = (
        "Codes dispatched by commands/close.md / commands/commit.md with "
        "no matching entries[].code in schemas/repair-map.v1.json:"
    )
    body = [
        "  - {code} ({locs})".format(code=code, locs=", ".join(f"{path}:{lineno}" for path, lineno in locations))
        for code, locations in missing
    ]
    return "\n".join([header, *body])


